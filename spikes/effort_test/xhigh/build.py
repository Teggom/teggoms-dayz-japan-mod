def wb(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(text if isinstance(text, bytes) else text.replace("\r\n", "\n").encode("utf-8"))


def model_path(state):
    return "\\%s\\%s.p3d" % (PREFIX, MODELS[state][0])


# ------------------------------------------------------------------------------------------------ configs
def config_cpp():
    cls = ""
    for st in ("A", "B"):
        p3d, cname, disp = MODELS[st]
        cls += ("\t// %s\n\tclass %s: HouseNoDestruct\n\t{\n\t\tscope=1;\n\t\tdisplayName=\"%s\";\n"
                "\t\tmodel=\"%s\";\n\t};\n"
                % ("state A: intact, every drawer shut, dusty" if st == "A" else
                   "state B: ransacked, the lock drawer on the floor in front, three drawers pulled out",
                   cname, disp, model_path(st)))
    return ("// %s - effort test (level %s): jp_f_tansu, the clothing chest of drawers (BUILD_LIST row 26), two states.\n"
            "// GENERATED by japan_dev/spikes/effort_test/%s/build.py - edit the generator, not this file.\n"
            "// Static furniture like vanilla StaticObj_Furniture_* (HouseNoDestruct, scope 1): placed by the object\n"
            "// spawner, init.c or as a proxy. Asset only: no world, map or mission dependency.\n"
            "class CfgPatches\n{\n\tclass %s\n\t{\n\t\tunits[]={};\n\t\tweapons[]={};\n\t\trequiredVersion=0.1;\n"
            "\t\trequiredAddons[]=\n\t\t{\n\t\t\t\"DZ_Data\",\n\t\t\t\"JP_Common\"\n\t\t};\n\t};\n};\n"
            "class CfgVehicles\n{\n\tclass HouseNoDestruct;\n%s};\n" % (PATCH, LEVEL, LEVEL, PATCH, cls))


def model_cfg():
    body = "".join("\tclass %s: Default\n\t{\n\t};\n" % MODELS[st][0] for st in ("A", "B"))
    return ("// static furniture: no skeleton, no animations\n"
            "class CfgSkeletons\n{\n\tclass Default\n\t{\n\t\tisDiscrete=1;\n\t\tskeletonInherit=\"\";\n"
            "\t\tskeletonBones[]={};\n\t};\n};\nclass CfgModels\n{\n\tclass Default\n\t{\n\t\tsectionsInherit=\"\";\n"
            "\t\tsections[]={};\n\t\tskeletonName=\"\";\n\t};\n%s};\n" % body)


def cfgconvert(path):
    os.makedirs(TEMP, exist_ok=True)
    dst = os.path.join(TEMP, os.path.basename(path) + ".bin")
    if os.path.isfile(dst):
        os.remove(dst)
    r = subprocess.run([CFGCONVERT, "-bin", "-dst", dst, path], capture_output=True, text=True, errors="replace")
    ok = r.returncode == 0 and os.path.isfile(dst)
    # and back to text, to prove the binary round-trips
    txt = dst + ".cpp"
    r2 = subprocess.run([CFGCONVERT, "-txt", "-dst", txt, dst], capture_output=True, text=True, errors="replace")
    ok2 = r2.returncode == 0 and os.path.isfile(txt)
    msg = (r.stdout + r.stderr + r2.stdout + r2.stderr).strip()
    print("  CfgConvert %s: %s %s" % (os.path.basename(path), "OK" if ok and ok2 else "FAILED", msg))
    return ok and ok2, msg


# ------------------------------------------------------------------------------------------------ steps
def write_models():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(SRC, exist_ok=True)
    infos = {}
    for st in ("A", "B"):
        part, info, L = tansu.lods(st)
        name = MODELS[st][0]
        mp = os.path.join(OUT, name + ".p3d")
        mlod.write_mlod(mp, L)
        shutil.copyfile(mp, os.path.join(SRC, name + ".p3d"))
        info["faces"] = {mlod.lod_name(l.resolution): len(l.faces) for l in L}
        info["tris_res1"] = sum(len(f[0]) - 2 for f in L[0].faces)
        infos[st] = info
        print("MLOD %s: %s, Res 1 = %d triangles" % (mp, info["faces"], info["tris_res1"]))
    wb(os.path.join(SRC, "model.cfg"), model_cfg())
    wb(os.path.join(SRC, "config.cpp"), config_cpp())
    return infos


