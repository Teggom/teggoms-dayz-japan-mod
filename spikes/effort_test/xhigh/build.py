BENIGN = [r"^No entry '\.", r"^Trying to access error value\.", r"CfgVehicles missing in PreloadConfig",
          r"Terrain grid 0\.5 will be too slow", r"is declared, but definition was not found",
          r"^Distance 0\.0 - min grid", r"^FileServer MaxCacheSize", r"^BINARIZE rev", r"^Binarize started",
          r"binarize\.exe\"? -always", r"^Convert model ", r"^<model = ", r"^</model>", r"KB saved in selections",
          r"DIAG-SERIALIZED BoundingCenter", r"^\s*$"]


def binarize():
    if not os.path.isdir(r"P:\DZ") or not os.path.isdir(r"P:\JP\effort_test\%s" % LEVEL):
        print(r"binarize: P:\DZ or P:\JP\effort_test\%s missing (subst P: D:\DayZToolsExtract; P:\JP junction)" % LEVEL)
        return False, {}
    out = os.path.join(TEMP, "binarized")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    cmd = [BINARIZE, "-always", "-addon=P:\\JP\\effort_test\\%s" % LEVEL, "-binpath=P:\\bin",
           "P:\\JP\\effort_test\\%s" % LEVEL, out, "*.p3d"]
    r = subprocess.run(cmd, cwd="P:\\", capture_output=True, text=True, errors="replace")
    log = os.path.join(OUT, "binarize.log")
    text = r.stdout + "\n" + r.stderr
    wb(log, " ".join(cmd) + "\n\n" + text)
    lines = [l for l in text.splitlines()]
    other = [l for l in lines if not any(re.search(b, l) for b in BENIGN)]
    flagged = [l for l in lines if re.search(r"error|warning|cannot|not loaded|missing|failed", l, re.I)
               and not any(re.search(b, l) for b in BENIGN)]
    res = {"returncode": r.returncode, "log": os.path.relpath(log, DEV), "lines": len(lines),
           "unexplained_lines": other, "flagged_lines": flagged, "converted": {}}
    ok = True
    for st in ("A", "B"):
        name = MODELS[st][0] + ".p3d"
        found = None
        for root_, _, files in os.walk(out):
            if name in files:
                found = os.path.join(root_, name)
        good = bool(found) and open(found, "rb").read(4) == b"ODOL"
        res["converted"][name] = {"odol": good, "bytes": os.path.getsize(found) if found else 0,
                                  "mentioned_in_log": any(name in l.lower() for l in lines)}
        if good:
            shutil.copyfile(found, os.path.join(SRC, name))
        ok = ok and good
    print("binarize %s: %s; %d log lines, %d unexplained, %d flagged -> %s" % (
        "OK" if ok else "FAILED", {k: v["bytes"] for k, v in res["converted"].items()}, len(lines), len(other),
        len(flagged), log))
    for l in other:
        print("   unexplained:", l)
    res["ok"] = ok and not flagged
    return ok, res


def pack():
    stage = os.path.join(TEMP, "pbo_stage")
    shutil.rmtree(stage, ignore_errors=True)
    shutil.copytree(SRC, stage, ignore=shutil.ignore_patterns("model.cfg", "*.json", "*.blend", "*.png", "*.log"))
    import pbo
    try:
        pbo.cmd_pack(stage, PBO_OUT, PREFIX)
        where = PBO_OUT
    except PermissionError as e:
        print("PBO write to @Japan\\addons FAILED (a running server or game locks it):", e)
        where = os.path.join(HERE, PBO_NAME)
        pbo.cmd_pack(stage, where, PREFIX)
    print("packed", where, os.path.getsize(where), "bytes")
    return where


def main(argv):
    infos = write_models()
    sidecar(infos)
    cc = [cfgconvert(os.path.join(SRC, "config.cpp")), cfgconvert(os.path.join(SRC, "model.cfg"))]
    bres = {}
    if "--no-binarize" not in argv:
        _, bres = binarize()
    where = None
    if "--no-pack" not in argv:
        where = pack()
    wb(os.path.join(OUT, "build_result.json"), json.dumps({
        "cfgconvert": {"config.cpp": {"ok": cc[0][0], "msg": cc[0][1]}, "model.cfg": {"ok": cc[1][0], "msg": cc[1][1]}},
        "binarize": bres, "pbo": where, "infos": infos}, indent=1, default=str) + "\n")
    import verify
    ok = verify.run()
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
