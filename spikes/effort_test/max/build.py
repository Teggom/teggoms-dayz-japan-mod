# ------------------------------------------------------------------------------------------------ checks
def _footprint(comp):
    """xz polygon (convex hull of the component's points) + y range: every component here is a vertical prism."""
    pts = comp["pts"]
    hull = tansu.core.hull2d([(round(p[0], 6), round(p[2], 6)) for p in pts])
    ys = [p[1] for p in pts]
    return hull, (min(ys), max(ys))


def _sat2d(a, b, pad=0.0):
    """True if convex polygons a and b overlap by more than pad (separating axis test)."""
    for poly in (a, b):
        for i in range(len(poly)):
            p0, p1 = poly[i], poly[(i + 1) % len(poly)]
            ax = (-(p1[1] - p0[1]), p1[0] - p0[0])
            ln = math.hypot(*ax) or 1.0
            ax = (ax[0] / ln, ax[1] / ln)
            pa = [q[0] * ax[0] + q[1] * ax[1] for q in a]
            pb = [q[0] * ax[0] + q[1] * ax[1] for q in b]
            if max(pa) <= min(pb) + pad or max(pb) <= min(pa) + pad:
                return False
    return True


def run_checks(res, bin_ok, bin_text, cfg_ok, pbo_path):
    out = {"level": LEVEL, "states": {}}
    allok = True
    for state, d in res.items():
        rows = []
        lods = mlod.read_mlod(d["mlod"])                      # read back from disk
        kit, counts = checks.check_part(d["part"], d["mlod"], lods)
        for name, ok, detail in kit:
            if name.startswith("C3"):
                continue                                     # grid snap: a prop has no post/sill connectors
            rows.append((name, ok, detail))
        L = {mlod.lod_name(l.resolution): l for l in lods}
        # LOD set (BUILD_LIST Q5 rule 2: furniture Res 1-3, Geometry, View, Fire; no Memory, no Roadway)
        want = ["Resolution 1", "Resolution 2", "Resolution 3", "Geometry", "View Geometry", "Fire Geometry"]
        rows.append(("C5 LOD set = vanilla furniture (Res 1-3, Geometry, View, Fire)", sorted(L) == sorted(want),
                     ", ".join(sorted(L))))
        for k, lim in BUDGET.items():
            rows.append(("C5 budget %s <= %d" % (k, lim), counts.get(k, 0) <= lim, "%d faces" % counts.get(k, 0)))
        g = L["Geometry"]
        rows.append(("Geometry props + mass", g.properties.get("autocenter") == "0" and abs(sum(g.mass) - MASS) < 0.01,
                     "props %s, mass %.2f kg on %d points" % (g.properties, sum(g.mass), len(g.points))))
        # C4 dimensions on the Res 1 wood carcass (fittings stand 2-11 mm proud and are excluded)
        r1 = L["Resolution 1"]
        wood_pts = set()
        for verts, _, tex, _ in r1.faces:
            if "wood_street_dark" in tex or "wood_sooted" in tex:
                wood_pts.update(v[0] for v in verts)
        body = [r1.points[i] for i in wood_pts if r1.points[i][2] <= tansu.Z1 + 1e-4 and
                -tansu.Z1 - 1e-4 <= r1.points[i][2] and r1.points[i][1] >= -1e-6]
        xs, ys, zs = [p[0] for p in body], [p[1] for p in body], [p[2] for p in body]
        # the two boxes = the two Geometry blocks tagged coll_box (components are numbered in solid order)
        gtags = [s.tag for s in d["part"].solids if s.geo and s.closed]
        blocks = sorted(c["bbox"] for c, tg in zip(checks.components(L["Geometry"]), gtags) if tg == "coll_box")
        joint = blocks[0][3] if len(blocks) == 2 and abs(blocks[0][3] - blocks[1][2]) < 1e-4 else -1.0
        dims = [("width", 1.00, max(xs) - min(xs)), ("depth", 0.45, max(zs) - min(zs)), ("height", 1.00, max(ys)),
                ("two stacked boxes of 0.50 (joint height)", 0.50, joint)]
        for nm, exp, got in dims:
            ok = abs(got - exp) <= max(0.005, 0.02 * exp)
            rows.append(("C4 %s" % nm, ok, "expected %.3f (BUILD_LIST row 26), measured %.4f" % (exp, got)))
        allp = r1.points
        miny = min(p[1] for p in allp)
        maxy = max(p[1] for p in allp)
        rows.append(("C4 drawers: 4, iron ring pulls 2 per drawer, side handles 4",
                     sum(1 for s in d["part"].solids if s.tag == "ring") == 8 and
                     sum(1 for s in d["part"].solids if s.tag == "grip") == 4, "rings %d, grips %d, locks %d" % (
                         sum(1 for s in d["part"].solids if s.tag == "ring"),
                         sum(1 for s in d["part"].solids if s.tag == "grip"),
                         sum(1 for s in d["part"].solids if s.tag == "lock"))))
        # C6 placement: base on the floor, no Res-1 point below it, top loot surface clear
        rows.append(("C6 base on the floor (0-2 cm)", abs(miny) <= 1e-4, "lowest point y = %.4f, top %.4f" % (miny, maxy)))
        comps = checks.components(g)
        fps = [(c["name"], _footprint(c)) for c in comps]
        # which component is which (order = the order of geo solids in the part)
        geo_tags = [s.tag for s in d["part"].solids if s.geo and s.closed]
        clash = []
        for i in range(len(fps)):
            for j in range(i + 1, len(fps)):
                ti, tj = geo_tags[i], geo_tags[j]
                same = (ti == tj == "geo_fd") or ({ti, tj} <= {"coll_box"})
                if same or {ti, tj} == {"coll_box", "coll_drawer"}:
                    continue                               # wall-to-wall joints of one piece / drawer against its box
                (pa, ya), (pb, yb) = fps[i][1], fps[j][1]
                if min(ya[1], yb[1]) - max(ya[0], yb[0]) > 0.01 and _sat2d(pa, pb, pad=0.01):
                    clash.append("%s(%s) x %s(%s)" % (fps[i][0], ti, fps[j][0], tj))
        rows.append(("C6 no interpenetration > 1 cm between separate pieces (Geometry)", not clash,
                     "%d components, %s" % (len(comps), "clear" if not clash else "; ".join(clash[:4]))))
        # loot: top points on the top, nothing above; dropped-drawer point inside its bottom, 25 cm clear above
        ls = tansu.loot_surfaces(state, d["meta"])
        lp_ok, det = True, []
        for s in ls:
            for p in s["points"]:
                # vertical rays at the point and at 8 points on its range circle, against the convex components
                samples = [(p[0], p[2])] + [(p[0] + s["range"] * math.cos(k * math.pi / 4),
                                             p[2] + s["range"] * math.sin(k * math.pi / 4)) for k in range(8)]
                above = []
                for x, z in samples:
                    for c in comps:
                        r = checks.ray_y(c, x, z)
                        if r and r[0] > p[1] + 0.005:
                            above.append(r[0] - p[1])
                support = []
                for c in comps:
                    r = checks.ray_y(c, p[0], p[2])
                    if r and abs(r[1] - p[1]) < 0.003:
                        support.append(c)
                clear = min(above) if above else 9.9
                okp = bool(support) and clear >= 0.25
                lp_ok = lp_ok and okp
                det.append("%s (%.3f, %.3f, %.3f): on %s, clear above %.2f m" % (s["name"], p[0], p[1], p[2],
                                                                                 support[0]["name"] if support else "NOTHING",
                                                                                 clear))
        rows.append(("C6 loot points on a Geometry top, >= 0.25 m clear above", lp_ok, "; ".join(det)))
        if state == "ransacked":
            # every drawer-box vertex inside the carcass depth lies in a drawer cavity (no board is pierced), the
            # drooped drawer included; its rear corner must end 0-2 mm under the board above
            cav = [tansu.opening(y0, sl) for _, y0, sl in tansu.DRAWERS]
            bad, worst = [], 1.0
            for s in d["part"].solids:
                if s.tag not in ("dside", "dback", "dbottom", "front") or 1 not in s.vis:
                    continue
                for v in s.verts:
                    if v[2] >= tansu.Z1 - 1e-6:
                        continue                               # in front of the carcass: nothing to pierce
                    inside = [(bb, tt) for bb, tt in cav if bb - 1e-6 <= v[1] <= tt + 1e-6]
                    okv = inside and abs(v[0]) <= tansu.XI + 1e-6 and v[2] >= tansu.Z0 + tansu.TB - 1e-6
                    if not okv:
                        bad.append(tuple(round(c, 4) for c in v))
                    else:
                        worst = min(worst, min(tt - v[1] for bb, tt in inside))
            dr = d["meta"].get("droop_deg", {})
            rows.append(("C6 drawer boxes inside their cavities (drooped drawer included)", not bad,
                         "%s; droop %s; closest approach to the board above %.4f m" % (
                             "all vertices inside" if not bad else "%d vertices outside, e.g. %s" % (len(bad), bad[:2]),
                             dr, worst)))
            fi = d["meta"]["floor_drawer"]
            fz = tansu.front_zone(state, d["meta"])
            inside = fz["z"][0] <= fi["z_rear"] and fi["z_front"] <= fz["z"][1]
            rows.append(("Dropped drawer inside the front zone", inside,
                         "drawer z %.3f..%.3f, zone z %.3f..%.3f, x %.3f..%.3f" % (fi["z_rear"], fi["z_front"], fz["z"][0],
                                                                                  fz["z"][1], fz["x"][0], fz["x"][1])))
        # C19 matte: the wood rvmats used carry the black env map; iron is glossy by design (T12)
        mats = sorted({f[3] for f in r1.faces})
        bad = []
        for m in mats:
            txt = open(os.path.join(DEV, "src", m), "rb").read().decode("latin-1")
            glossy = "metal_iron" in m
            black = "color(0,0,0,1,CO)" in txt and "fresnel(0.01,0.01)" in txt
            if not glossy and not black:
                bad.append(m)
        rows.append(("C19 matte finish (non-glossy rvmats have the black env map)", not bad,
                     "%d rvmats: %s" % (len(mats), ", ".join(os.path.basename(m) for m in mats))))
        # ODOL read-back
        if d.get("odol"):
            data = open(os.path.join(SRC, d["name"] + ".p3d"), "rb").read()
            nl = int.from_bytes(data[8:12], "little")
            import struct
            ress = struct.unpack_from("<%df" % nl, data, 12)
            rows.append(("ODOL in src (binarized, version %d)" % int.from_bytes(data[4:8], "little"),
                         data[:4] == b"ODOL" and nl == len(lods),
                         "%d LODs: %s" % (nl, ", ".join(mlod.lod_name(r) for r in ress))))
        n_ok = sum(1 for r in rows if r[1])
        allok = allok and n_ok == len(rows)
        out["states"][state] = {"faces": counts, "checks": [{"check": a, "ok": bool(b), "detail": c} for a, b, c in rows]}
        print("\n== checks %s: %d/%d" % (state, n_ok, len(rows)))
        for a, b, c in rows:
            print("  %s %s: %s" % ("OK  " if b else "FAIL", a, c))
    out["binarize_ok"] = bin_ok
    out["cfgconvert_ok"] = cfg_ok
    out["pbo"] = pbo_path
    wb(os.path.join(HERE, "checks.json"), json.dumps(out, indent=1))
    return allok


def main(argv):
    res = write_models()
    wb(os.path.join(SRC, "config.cpp"), config_cpp())
    cfg_ok, _ = cfgconvert(os.path.join(SRC, "config.cpp"))
    bin_ok, bin_text = (None, "")
    if "--no-binarize" not in argv:
        bin_ok, bin_text = binarize(res)
    sidecar(res)
    pbo_path = None
