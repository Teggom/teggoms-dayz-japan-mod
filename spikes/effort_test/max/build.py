def cfgconvert(path):
    tmp = os.path.join(OUT, "cfgconvert")
    os.makedirs(tmp, exist_ok=True)
    binp = os.path.join(tmp, "config.bin")
    txtp = os.path.join(tmp, "config_roundtrip.cpp")
    for p in (binp, txtp):
        if os.path.isfile(p):
            os.remove(p)
    r1 = subprocess.run([CFGCONVERT, "-bin", "-dst", binp, path], capture_output=True, text=True, errors="replace")
    r2 = subprocess.run([CFGCONVERT, "-txt", "-dst", txtp, binp], capture_output=True, text=True, errors="replace")
    ok = r1.returncode == 0 and os.path.isfile(binp) and r2.returncode == 0 and os.path.isfile(txtp)
    log = "CfgConvert -bin: rc=%d %s\nCfgConvert -txt: rc=%d %s\n" % (r1.returncode, (r1.stdout + r1.stderr).strip(),
                                                                    r2.returncode, (r2.stdout + r2.stderr).strip())
    classes = []
    if ok:
        txt = open(txtp, "rb").read().decode("utf-8", "replace")
        classes = re.findall(r"class\s+(\w+)", txt)
        want = [PATCH, "HouseNoDestruct", STATES[0][2], STATES[1][2]]
        miss = [c for c in want if c not in classes]
        models = re.findall(r'model\s*=\s*"([^"]+)"', txt)
        ok = ok and not miss and len(models) == 2
        log += "round trip classes: %s; models: %s; missing: %s\n" % (classes, models, miss)
    wb(os.path.join(OUT, "cfgconvert.log"), log)
    print("  CfgConvert config.cpp: %s (%s)" % ("OK" if ok else "FAILED", os.path.join(OUT, "cfgconvert.log")))
    return ok, log


