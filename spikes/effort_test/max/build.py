def write_models():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(SRC, exist_ok=True)
    res = {}
    for state, name, cname, disp in STATES:
        part, meta = tansu.build(state)
        lods = part.lods(geo_props=GEO_PROPS, mass=MASS)
        mp = os.path.join(OUT, name + ".p3d")
        mlod.write_mlod(mp, lods)
        copy_retry(mp, os.path.join(SRC, name + ".p3d"))
        faces = {mlod.lod_name(l.resolution): len(l.faces) for l in lods}
        print("MLOD %s: %s" % (mp, faces))
        res[state] = dict(part=part, meta=meta, lods=lods, mlod=mp, name=name, cls=cname, faces=faces)
    return res


def binarize(res):
    if not os.path.isdir(r"P:\DZ") or not os.path.isdir(r"P:\JP\effort_test\%s" % LEVEL):
        print(r"binarize: P:\DZ or P:\JP\effort_test\%s missing (subst P: D:\DayZToolsExtract; P:\JP junction)" % LEVEL)
        return False, ""
    out = os.path.join(OUT, "binarized")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    cmd = [BINARIZE, "-always", "-addon=P:\\%s" % PREFIX, "-binpath=P:\\bin", "P:\\%s" % PREFIX, out, "*.p3d"]
    r = subprocess.run(cmd, cwd="P:\\", capture_output=True, text=True, errors="replace")
    log = os.path.join(OUT, "binarize.log")
    wb(log, " ".join(cmd) + "\n\n" + r.stdout + "\n" + r.stderr)
    text = r.stdout + r.stderr
    # the lines that are about OUR models or files (the rest is binarize's usual world/config noise, as in the
    # machiya log: No entry '.CfgWorlds' ..., Terrain grid ...)
    # Known benign: "Note: 'HouseNoDestruct' is declared, but definition was not found. Creating empty class" -
    # binarize loads only this addon's config, not DZ_Data (the machiya log has the same note).
    ours = [l for l in text.splitlines() if re.search(r"jp_f_tansu|effort_test|jp\\common", l, re.I)
            and re.search(r"error|warning|cannot|not found|missing|failed", l, re.I)
            and not re.search(r"'HouseNoDestruct' is declared, but definition was not found", l)]
    ok = r.returncode == 0
    for state, d in res.items():
        found = os.path.join(out, d["name"] + ".p3d")
        if os.path.isfile(found) and open(found, "rb").read(4) == b"ODOL":
            copy_retry(found, os.path.join(SRC, d["name"] + ".p3d"))
            d["odol"] = found
        else:
            ok = False
    bc = re.findall(r"BoundingCenter of (\S+): ([-\d., ]+)", text)
    print("binarize %s: rc=%d, %d problem lines about our files, bounding centres %s (%s)"
          % ("OK" if ok and not ours else "FAILED", r.returncode, len(ours), bc, log))
    return ok and not ours, text


def pack():
    stage = os.path.join(OUT, "pbo_stage")
    shutil.rmtree(stage, ignore_errors=True)
    shutil.copytree(SRC, stage, ignore=shutil.ignore_patterns("model.cfg", "*.blend", "*.png", "*.log"))
    import pbo
    try:
        pbo.cmd_pack(stage, PBO_OUT, PREFIX)
        where = PBO_OUT
    except PermissionError as e:
        where = os.path.join(OUT, PBO_NAME)
        print("PBO write to @Japan FAILED (a running server or game locks it): %s -> packing into %s" % (e, where))
        pbo.cmd_pack(stage, where, PREFIX)
    print("packed", where, os.path.getsize(where), "bytes")
    return where


