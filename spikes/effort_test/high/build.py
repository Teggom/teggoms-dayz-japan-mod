#!/usr/bin/env python3
r"""build.py - effort test (LEVEL = high): jp_f_tansu in two states -> jp_efftest_high.pbo

  python build.py [--no-binarize] [--no-pack]

  1. MLOD for both states (tansu.py) -> out/*.p3d, copied to src/JP/effort_test/high/data/
  2. config.cpp (CfgPatches JP_EffTest_high, two HouseNoDestruct statics) + model.cfg -> CfgConvert
  3. binarize.exe (cwd P:\) -> ODOL replaces the MLOD copies in src (MLODs stay in out/)
  4. pack src/JP/effort_test/high (minus model.cfg and sidecars) -> ..\@Japan\addons\jp_efftest_high.pbo
  5. checks -> checks.json
Never touches the server, the game or any GUI program. Writes only in this folder, src/JP/effort_test/high and
the one PBO.
"""
