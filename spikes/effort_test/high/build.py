def wb(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(text if isinstance(text, bytes) else text.replace("\r\n", "\n").encode("utf-8"))


def model_path(p3d):
    return "\\%s\\data\\%s.p3d" % (PREFIX, p3d)


def config_cpp():
    cls = ""
    for st, (p3d, cname, disp) in MODELS.items():
        cls += ("\t// %s\n\tclass %s: HouseNoDestruct\n\t{\n\t\tscope=1;\n\t\tdisplayName=\"%s\";\n"
                "\t\tmodel=\"%s\";\n\t};\n" % (st, cname, disp, model_path(p3d)))
    units = ", ".join('"%s"' % m[1] for m in MODELS.values())
    return ("// %s - effort test prop jp_f_tansu (BUILD_LIST row 26), two states. Placeable statics like vanilla\n"
            "// StaticObj_Furniture_* (HouseNoDestruct, scope 1: object spawner / init.c).\n"
            "// GENERATED by japan_dev/spikes/effort_test/%s/build.py - edit the generator, not this file.\n"
            "class CfgPatches\n{\n\tclass %s\n\t{\n\t\tunits[]={%s};\n\t\tweapons[]={};\n"
            "\t\trequiredVersion=0.1;\n\t\trequiredAddons[]=\n\t\t{\n\t\t\t\"DZ_Data\",\n\t\t\t\"JP_Common\"\n"
            "\t\t};\n\t};\n};\nclass CfgVehicles\n{\n\tclass HouseNoDestruct;\n%s};\n"
            % (PATCH, LEVEL, PATCH, units, cls))


def model_cfg():
    models = "".join("\tclass %s: Default\n\t{\n\t};\n" % m[0] for m in MODELS.values())
    return ("class CfgSkeletons\n{\n\tclass Default\n\t{\n\t\tisDiscrete=1;\n\t\tskeletonInherit=\"\";\n"
            "\t\tskeletonBones[]={};\n\t};\n};\nclass CfgModels\n{\n\tclass Default\n\t{\n\t\tsectionsInherit=\"\";\n"
            "\t\tsections[]={};\n\t\tskeletonName=\"\";\n\t};\n%s};\n" % models)


def cfgconvert(path):
    os.makedirs(TEMP, exist_ok=True)
    dst = os.path.join(TEMP, os.path.basename(path) + ".bin")
    if os.path.exists(dst):
        os.remove(dst)
    r = subprocess.run([CFGCONVERT, "-bin", "-dst", dst, path], capture_output=True, text=True, errors="replace")
    ok = r.returncode == 0 and os.path.isfile(dst)
    back = dst + ".cpp"
    if ok:   # round trip: bin -> txt, proves the binary parses too
        r2 = subprocess.run([CFGCONVERT, "-txt", "-dst", back, dst], capture_output=True, text=True, errors="replace")
        ok = r2.returncode == 0 and os.path.isfile(back)
    msg = "CfgConvert %s: %s %s" % (os.path.basename(path), "OK" if ok else "FAILED", (r.stdout + r.stderr).strip())
    print("  " + msg)
    return ok, msg


def write_models():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(DDIR, exist_ok=True)
    res = {}
    for st, (p3d, cname, _) in MODELS.items():
        P = TZ.model(st)
        lods = P.lods(TZ.geo_props(), TZ.MASS)
        mp = os.path.join(OUT, p3d + ".p3d")
        mlod.write_mlod(mp, lods)
        shutil.copyfile(mp, os.path.join(DDIR, p3d + ".p3d"))
        res[st] = (P, lods, mp)
        print("MLOD %s: %s" % (p3d, {mlod.lod_name(l.resolution): len(l.faces) for l in lods}))
    note = {"id": "jp_f_tansu", "build_list_row": 26, "frame": "model: origin = footprint centre on the floor, +z = "
            "drawer front, autocenter=0", "loot_surfaces": {}}
    for st, (P, lods, mp) in res.items():
        pts = []
        for k in sorted(P.memory):
            if k.startswith("loot_"):
                p = P.memory[k][0]
                pts.append({"memory_point": k, "model": [round(c, 4) for c in p],
                            "range": 0.2 if k.startswith("loot_top") else 0.15,
                            "kind": "shelf (top at 1.00)" if k.startswith("loot_top") else "floor (dropped drawer)"})
        note["loot_surfaces"][MODELS[st][1]] = pts
    note["rule"] = "BUILD_LIST 26: top at 1.00: 2 points (range 0.2); ransacked: 1 point in the dropped drawer (floor)"
    wb(os.path.join(DDIR, "jp_f_tansu.loot.json"), json.dumps(note, indent=1))
    wb(os.path.join(DDIR, "model.cfg"), model_cfg())
    wb(os.path.join(SRC, "config.cpp"), config_cpp())
    return res


def binarize():
    out = os.path.join(TEMP, "binarized")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    cmd = [BINARIZE, "-always", "-addon=P:\\" + PREFIX, "-binpath=P:\\bin", "P:\\%s\\data" % PREFIX, out, "*.p3d"]
    r = subprocess.run(cmd, cwd="P:\\", capture_output=True, text=True, errors="replace")
    log = os.path.join(HERE, "binarize.log")
    wb(log, " ".join(cmd) + "\n\n" + r.stdout + "\n" + r.stderr)
    # the same 8 environment lines appear in every JP binarize log (machiya_t3_01/out/binarize.log): binarize runs
    # without the game's global config (CfgDefaultSettings, CfgWorlds, PreloadConfig). Anything else is a finding.
    noise = (r"^Warning: Terrain grid", r"^Warning: CfgVehicles missing in PreloadConfig", r"^Trying to access error value")
    lines = (r.stdout + r.stderr).splitlines()
    bad = [l for l in lines if re.search(r"error|warning|cannot|not loaded|missing", l, re.I)
           and not any(re.search(n, l) for n in noise)]
    boiler = sum(1 for l in lines if any(re.search(n, l) for n in noise))
    ok = True
    info = {}
    for st, (p3d, _, _) in MODELS.items():
        found = None
        for root_, _, files in os.walk(out):
            if p3d + ".p3d" in files:
                found = os.path.join(root_, p3d + ".p3d")
        if found and open(found, "rb").read(4) == b"ODOL":
            shutil.copyfile(found, os.path.join(DDIR, p3d + ".p3d"))
            info[st] = os.path.getsize(found)
        else:
            ok = False
            info[st] = None
    print("binarize %s: %s; %d warning/error lines (log %s)" % ("OK" if ok else "FAILED", info, len(bad), log))
    for l in bad[:20]:
        print("   ", l)
    return ok, {"odol_bytes": info, "warning_lines": bad, "boilerplate_lines": boiler, "exit": r.returncode}


def pack():
    stage = os.path.join(TEMP, "pbo_stage")
    shutil.rmtree(stage, ignore_errors=True)
    shutil.copytree(SRC, stage, ignore=shutil.ignore_patterns("model.cfg", "*.json", "*.png", "*.log"))
    import pbo
    try:
        pbo.cmd_pack(stage, PBO_OUT, PREFIX)
        return True, PBO_OUT
    except PermissionError as e:
        print("PBO write to @Japan FAILED (locked by a running server/game?):", e)
        pbo.cmd_pack(stage, PBO_FALLBACK, PREFIX)
        return False, PBO_FALLBACK


