def item(cls, parent, disp, desc, folder, stem, tex, slot, info, hp, armor="", personality=False, extra=""):
    base = "JP\\characters\\%s" % folder
    rv = "%s\\data\\%s" % (base, tex)
    hs = '"camoGround", "camoMale", "camoFemale"' + (', "personality"' if personality else "")
    return """	class %(cls)s: %(parent)s
	{
		scope = 2;
		displayName = "%(disp)s";
		descriptionShort = "%(desc)s";
		model = "\\%(base)s\\%(stem)s_g.p3d";
		inventorySlot[] = {"%(slot)s"};
		itemInfo[] = {"Clothing", "%(info)s"};
		hiddenSelections[] = {%(hs)s};
		hiddenSelectionsTextures[] =
		{
			"%(base)s\\data\\%(tex)s_co.paa",
			"%(base)s\\data\\%(tex)s_co.paa",
			"%(base)s\\data\\%(tex)s_co.paa"
		};%(extra)s
		class ClothingTypes
		{
			male = "\\%(base)s\\%(stem)s_m.p3d";
			female = "\\%(base)s\\%(stem)s_f.p3d";
		};
		class DamageSystem
		{
			class GlobalHealth
			{
				class Health
				{
					hitpoints = %(hp)d;
					healthLevels[] = %(hl)s;
				};
			};%(armor)s
		};
	};
""" % dict(cls=cls, parent=parent, disp=disp, desc=desc, base=base, stem=stem, tex=tex, slot=slot, info=info, hs=hs,
           hp=hp, hl=health_levels(rv), armor=armor, extra=extra)


