def all_models():
    return dict(MODELS)


def health_levels(rv):
    lv = [(1.0, ""), (0.7, ""), (0.5, "_damage"), (0.3, "_damage"), (0.0, "_destruct")]
    rows = []
    for h, suf in lv:
        rows.append('\t\t\t\t\t\t{%s, {"%s%s.rvmat"}}' % (("%g" % h), rv, suf))
    return "{\n" + ",\n".join(rows) + "\n\t\t\t\t\t}"


