"""config.cpp for jp_characters.pbo (CfgPatches JP_Characters). Generated; edit here, not in src.

Each item subclasses a vanilla clothing base so slot, insulation (heatIsolation), wetness, cargo, sounds and
repair are inherited unchanged. What is redefined:
  - model / ClothingTypes / hiddenSelections(+Textures) - our meshes and textures
  - DamageSystem: a child's `class DamageSystem` would not inherit the parent's nested classes, so the parent's
    values (hitpoints, GlobalArmor) are copied verbatim from the vanilla config and only healthLevels point at
    our rvmats (pristine / damage / destruct), which is what makes the damage states show on our textures.
"""
